function expand(rows: TopicTuple[]): PlayTopic[] {
  return rows.map((r) => ({
    slug: r[0], unitGroup: r[1], title: r[2], simpleSummary: r[3],
    howToDo: r[4], whenToUse: r[5], commonMistake: r[6], counterOrTip: r[7],
    moduleType: r[8], positions: r[9], pose: r[10],
    startPos: [r[11], r[12]], endPos: [r[13], r[14]], ballTarget: [r[15], r[16]],
    ...(r[17] != null && r[18] != null ? { matePos: [r[17], r[18]] as [number, number] } : {}),
  }));
}

